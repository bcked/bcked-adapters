"""Downloads all Tether assurance reports listed on https://tether.to/en/transparency/.

Usage: python3 fetch_tether.py <output dir> > reports.json

Prints a list of {"date", "name", "file"} for every report. The report list comes from the page data
of the transparency page, which is generated by Gatsby.
"""
import json
import os
import sys
import urllib.request

PAGE_DATA = "https://tether.to/page-data/en/transparency/page-data.json"
HEADERS = {"User-Agent": "Mozilla/5.0"}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=60) as response:
        return response.read()


def main(out):
    os.makedirs(out, exist_ok=True)
    nodes = json.loads(get(PAGE_DATA))["result"]["data"]["reports"]["nodes"]
    reports = []
    for node in nodes:
        url = "https:" + node["reportFile"]["file"]["url"]
        path = os.path.join(out, os.path.basename(url))
        if not os.path.exists(path):
            with open(path, "wb") as f:
                f.write(get(url))
        reports.append({"date": node["reportDate"], "name": node["reportName"], "file": path})
    print(json.dumps(reports, indent=2))


if __name__ == "__main__":
    main(sys.argv[1])
